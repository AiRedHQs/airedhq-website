import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const registry = [
  ["01-ai-jobs-india-2026.md", "careers", "ai-jobs-india-2026"],
  ["02-ats-friendly-resume.md", "careers", "ats-friendly-resume"],
  ["03-job-search-strategies-freshers-experienced.md", "careers", "job-search-strategies"],
  ["04-ai-in-recruitment-screening-hiring.md", "careers", "ai-in-recruitment"],
  ["05-best-local-markets-city-template.md", "local-discovery", "find-the-best-local-markets"],
  ["06-find-trusted-local-businesses-near-you.md", "local-discovery", "find-trusted-local-businesses"],
  ["07-best-markets-near-me-clothes-electronics-food-home.md", "local-discovery", "best-markets-near-me"],
  ["08-ai-powered-local-discovery-nearby-businesses.md", "local-discovery", "ai-powered-local-discovery"],
  ["09-create-personal-financial-plan-step-by-step.md", "financial-planning", "create-a-personal-financial-plan"],
  ["10-sip-calculator-financial-goals.md", "financial-planning", "sip-calculator-guide"],
  ["11-retirement-planning-india-corpus.md", "financial-planning", "retirement-planning-india"],
  ["12-emergency-fund-calculator-monthly-savings.md", "financial-planning", "emergency-fund-calculator"],
  ["13-ar-vr-labs-schools-setup-implementation.md", "immersive-learning", "ar-vr-labs-in-schools"],
  ["14-ar-vr-lab-setup-cost-schools-india.md", "immersive-learning", "ar-vr-lab-cost-india"],
  ["15-ar-vr-labs-student-learning-engagement-skills.md", "immersive-learning", "ar-vr-learning-outcomes"],
];
const categoryInfo = {
  careers: ["Careers and Recruitment", "#8a4cff"],
  "local-discovery": ["Local Discovery", "#2f91e8"],
  "financial-planning": ["Financial Planning", "#8bdc34"],
  "immersive-learning": ["Immersive Learning", "#e83e9b"],
};

const manifest = await Promise.all(registry.map(async ([sourceFile, category, slug]) => {
  const { data } = matter(await readFile(path.join(root, "public", "Blogs", sourceFile), "utf8"));
  const generic = sourceFile.startsWith("05-");
  const [categoryLabel, accent] = categoryInfo[category];
  const title = generic ? "How to Find the Best Local Markets in Any City" : String(data.title ?? slug);
  const description = generic
    ? "A practical framework for finding, comparing and verifying useful local markets in any city."
    : String(data.description ?? "Practical guidance from the AiRedHQ editorial team.");
  return {
    sourceFile, slug, route: `/blog/${category}/${slug}`, category, categoryLabel, accent,
    frontmatter: {
      title, description,
      readingTime: generic ? "18 minutes" : String(data.readingTime ?? "20 minutes"),
      updatedAt: String(data.updatedAt ?? data.publishedAt ?? "2026-07-30").slice(0, 10),
    },
    heroVisual: {
      src: `/blog/images/${slug}-hero.webp`,
      alt: title,
      caption: `${title} — an original editorial visual by AiRedHQ.`,
    },
  };
}));

const output = `// Generated by scripts/generate-blog-manifest.mjs.\nimport type { BlogArticleSummary } from "@/src/types/blog";\nexport const blogManifest = ${JSON.stringify(manifest, null, 2)} as const satisfies readonly BlogArticleSummary[];\n`;
await mkdir(path.join(root, "src", "generated"), { recursive: true });
await writeFile(path.join(root, "src", "generated", "blog-manifest.ts"), output, "utf8");
console.log(`Generated metadata for ${manifest.length} blog articles.`);
